#!/bin/bash
# Zip this folder tree into ../<folder name>.zip, leaving out build
# artifacts (the same things .gitignore lists). Needs zip (Info-ZIP).
# Always works on the folder this script is in, not the current folder.
# Don't name a variable ZIP: zip reads default options from it.

set -e
cd "$(dirname "$0")"

folder=$(basename "$PWD")
zipfile="../${folder}.zip"
echo "Zipping to: $zipfile"
rm -f "$zipfile"

# -r recurse, -S include hidden and system files, -D no folder entries,
# -X no extra file attributes.
# build/*: CMake output tree; out/*, .vs/*: Visual Studio.
# src/version.h: generated by CMake. Smalltalk/Examples/*/*.img: the images
# of the examples' build.sh. bin/lst: the copy of lst the build makes.
# bin/*.img: the images the build, build.sh and the VS Code launch configs write.
# The rest: compiler output anywhere (bin/lst.exe too).
zip -r -S -D -X "$zipfile" . -x \
    "build/*" \
    "out/*" \
    ".vs/*" \
    "src/version.h" \
    "Smalltalk/Examples/*/*.img" \
    "bin/lst" \
    "bin/*.img" \
    "*.o" "*.obj" "*.pdb" "*.ilk" "*.exe" "*~"

echo "Done."
